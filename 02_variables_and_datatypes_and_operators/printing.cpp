#include <iostream>
using namespace std;

int main() {
    int age = 18;

    // method 1: printing everything in single line
    // output: my name is teena and i am 18 years old
    cout << "my name is teena " << "and i am " << age << " years old" << endl;

    // method 2: printing in multiple lines
    // output: my name is teena
    //         and i am 18 years old
    cout << "my name is teena" << endl;
    cout << "and i am " << age << " years old" << endl;

    return 0;
}
   
    
